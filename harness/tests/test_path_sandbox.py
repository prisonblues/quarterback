"""The PATH sandbox itself: absent has to mean absent (#385, #472).

`_path_sandbox` is a fixture, and a fixture that quietly stops working takes
every suite built on it with it — silently, and in the direction that reads as
success. #472 is exactly that: three suites asserted what a stanza does with
`qb-claim` / `qb-release` / `qb-admit` missing, built their PATH out of
`dirname(bash)` to get `git` and `jq`, and on a home-manager install that
directory IS the profile directory holding those three tools. The absent branch
was never taken. A fourth suite passed anyway and had never taken it either.

So the module's guarantee is asserted here, on this host, with the real tools
installed — the configuration under which the old idiom failed. Two of these
tests would have caught #472 the day it was written.

Run: pytest harness/tests
"""

from __future__ import annotations

import io
import json
import os
import shutil
import subprocess
import sys
import tokenize
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _path_sandbox  # noqa: E402

TESTS = Path(__file__).resolve().parent

#: The two triple-quote openers, spelled without writing either of them
#: inside this file's own source.
TQ1, TQ2 = chr(34) * 3, chr(39) * 3

#: The suites whose subject is a tool being missing. They are named rather than
#: discovered because the property is about intent — a suite that asserts on an
#: absent tool owes its PATH to this module — and a discovered list would go
#: quiet the moment somebody spelled the absence differently.
ABSENCE_SUITES = (
    "test_create_worktree_claim.py",
    "test_create_worktree_bound.py",
    "test_prune_worktrees_claims.py",
    "test_remove_worktree_claim.py",
    # #528's three. Each asserted what happens with a `qb-*` missing while the
    # inherited PATH supplied it: `qb-catchup` ran once per run under a test
    # named "no qb-catchup on PATH", the `lonely-bin/` copy meant to defeat the
    # `${0%/*}` fallback was undone by the PATH beside it, and a deleted stub
    # `qb-claim` was replaced by the installed one.
    "test_qb_hook_end.py",
    "test_worktree_holder.py",
    "test_qb_start.py",
)

#: The wider set: every suite that hands a real harness script a whole
#: ENVIRONMENT. A superset of the above, because "the tool is absent" is only one
#: of the two ways a test can end up running production code — the other is
#: running a tool on purpose with the developer's credential still in reach, and
#: `test_remove_worktree_branch_guard.py` did exactly that for three authenticated
#: calls to the live board per run (#528). Absence is a PATH property; a
#: credential is a HOME one; both are built in `_path_sandbox`.
ISOLATED_SUITES = ABSENCE_SUITES + (
    "test_remove_worktree_branch_guard.py",
    "test_qbdata.py",
)

#: The bash member of the same class. It cannot import the module, so what is
#: pinned is that its two runners still hand the scripts an environment.
SHELL_SUITE = "create_worktree_nginx.test.sh"

#: The config file this box actually has, if it has one. Named here so the tests
#: below can assert a sandbox environment does not resolve to it — the property
#: is "not the developer's", and on a machine with no config at all there is
#: nothing to be wrong about, which is why the assertions that use this skip.
REAL_CONFIG = Path(
    os.environ.get("QUARTERBACK_CONFIG")
    or os.path.join(os.environ.get("XDG_CONFIG_HOME")
                    or os.path.expanduser("~/.config"), "quarterback", "config"))

#: A stand-in for it, in the shape the real one has on this fleet: comments, a
#: `_CMD` rather than a literal token, a value quoting `$HOME`, and a human URL.
#: Copied off the installed file rather than imagined — a fixture that invents the
#: shape of the thing it stands for is how #531 shipped twelve tests that could
#: not fail.
DECOY_CONFIG = """\
# Generated by home/scripts.nix — do not edit; edit the fleet and rebuild.
# Host: decoybox
QUARTERBACK_BASE_URL=http://decoy.invalid
QUARTERBACK_TOKEN_CMD="printf decoy-token"
QUARTERBACK_REPO="$HOME/source/quarterback"
QUARTERBACK_HUMAN_URL=http://decoy-human.invalid
"""


def code_of(src: str) -> str:
    """`src` with its comments and docstrings blanked out, and nothing else.

    The coupling guard below is about what a suite DOES, and these files now
    explain at length what they no longer do — a ban that fired on its own
    explanation would be a guard nobody could document around.

    Comments and TRIPLE-quoted strings only. Blanking every string literal would
    be the tidier rule and it is wrong: `os.environ["PATH"]` is one of the banned
    idioms and it has a string inside it, so a guard that ate string literals
    would stop seeing the very thing it is looking for. Blanked in place rather
    than deleted, so everything else stays exactly where it was.
    """
    triples = (TQ1, TQ2)
    lines = src.splitlines(keepends=True)
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        prose = tok.type == tokenize.COMMENT or (
            tok.type == tokenize.STRING
            and tok.string.lstrip("rbuRBUf").startswith(triples))
        if not prose:
            continue
        (first, col), (last, end) = tok.start, tok.end
        for row in range(first, last + 1):
            line = lines[row - 1]
            a = col if row == first else 0
            b = end if row == last else len(line.rstrip("\r\n"))
            lines[row - 1] = line[:a] + " " * (b - a) + line[b:]
    return "".join(lines).replace("'", '"')


