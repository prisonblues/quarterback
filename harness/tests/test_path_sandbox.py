def test_the_pace_gate_is_off_unless_a_test_asks_for_it(tmp_path):
    """`qb-pace` reads the developer's own subscription and calls the usage
    endpoint, and `qb-seats` starts it by default. PATH cannot reach it — the
    fallback is `${0%/*}/qb-pace` inside `harness/bin` — so the knob is the seam.
    """
    assert _path_sandbox.sandbox_env(tmp_path)["QB_SEATS_PACE"] == "off"
    assert _path_sandbox.sandbox_env(tmp_path, QB_SEATS_PACE="obey")["QB_SEATS_PACE"] == "obey"


def test_the_path_guarantee_survives_the_environment_wrapper(tmp_path):
    """`sandbox_env` is the only thing most call sites now use, so the absence
    property has to hold through it as well as through `sandbox_path`."""
    bindir = tmp_path / "bin"
    bindir.mkdir()
    env = _path_sandbox.sandbox_env(tmp_path, bindir, tools=("git",))
    found = {t: shutil.which(t, path=env["PATH"]) for t in _path_sandbox.harness_tools()}
    assert not {k: v for k, v in found.items() if v is not None}
    assert shutil.which("git", path=env["PATH"])


def test_inherit_path_keeps_the_hosts_tools_and_none_of_its_credentials(tmp_path):
    """The escape hatch, and the half of the property it must NOT relax."""
    env = _path_sandbox.sandbox_env(tmp_path, inherit_path=True)
    assert shutil.which("bash", path=env["PATH"])
    assert Path(env["HOME"]).resolve().is_relative_to(tmp_path.resolve())
    assert not Path(_path_sandbox.config_path(env)).exists()


def test_an_empty_path_does_not_become_the_current_directory(tmp_path, monkeypatch):
    """An empty PATH entry means `.`, so joining a directory onto an absent PATH
    would put whatever the child's cwd happens to be on its own PATH."""
    monkeypatch.delenv("PATH", raising=False)
    env = _path_sandbox.sandbox_env(tmp_path, tmp_path / "bin", inherit_path=True)
    assert "" not in env["PATH"].split(os.pathsep)
